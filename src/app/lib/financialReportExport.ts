function readableReportRange(from: string, through: string) {
  const start = new Date(from + "T00:00:00Z");
  const end = new Date(through + "T00:00:00Z");
  const full = new Intl.DateTimeFormat("en-US", { dateStyle: "long", timeZone: "UTC" });
  const monthDay = new Intl.DateTimeFormat("en-US", { month: "long", day: "numeric", timeZone: "UTC" });
  if (from === through) return full.format(end);
  return (start.getUTCFullYear() === end.getUTCFullYear() ? monthDay : full).format(start) + " – " + full.format(end);
}

export function statementHtml(brand: ReportBrand | string, report: FinancialReport, expenseCoverageConfirmed = false) {
  const profitUndetermined = !expenseCoverageConfirmed || report.reviewCount > 0;
  const undated = report.exceptions.filter(row => row.reason === "Confirmed receipt with unknown date").reduce((sum, row) => sum + row.gross, 0);
  const exceptional = report.exceptions.reduce((sum, row) => sum + row.gross, 0) - undated;
  const rows = statementLines(report).map(([label, cents], index, lines) => {
    const last = index === lines.length - 1;
    const style = last ? "result" : label.startsWith("Total ") || label === "Gross profit" ? "subtotal" : "";
    const heading = profitUndetermined && last ? "Net profit" : profitUndetermined && label === "Gross profit" ? "Gross profit from recorded costs" : label;
    return `<tr class="${style}"><td>${escape(heading)}</td><td>${last && profitUndetermined ? "Undetermined" : displayCents(cents)}</td></tr>`;
  }).join("");
  const notes = [
    profitUndetermined && "Expense records are incomplete or unconfirmed. Expense totals show recorded amounts only. Net profit is undetermined.",
    report.draft && "Figures reflect supported transactions within the selected period.",
    "Sales tax excluded from supported receipts: " + displayCents(report.receipts.reduce((sum, row) => sum + row.tax, 0)) + ".",
    undated > 0 && "Confirmed receipts with unknown dates, excluded from the period: " + displayCents(undated) + ".",
    exceptional > 0 && "Other receipt or paid-balance evidence requiring reconciliation: " + displayCents(exceptional) + ". See the transaction export for references.",
    report.reviewCount > 0 && report.reviewCount + " transactions in this period require classification.",
  ].filter(Boolean).map(note => "<p>" + escape(String(note)) + "</p>").join("");
  const body = '<table><thead><tr><th scope="col">Account</th><th scope="col">Amount</th></tr></thead><tbody>'
    + rows + "</tbody></table><h2>Reporting notes</h2>" + notes;
  return reportHtml(typeof brand === "string" ? { name: brand } : brand, "Profit & Loss",
    readableReportRange(report.range.from, report.range.through), "Cash basis · USD", report.draft || profitUndetermined, body);
}

export function financialCsv(report: FinancialReport) {
  const rows: (string | number)[][] = [["Type", "Date", "Reference", "Description", "Category or exception", "Amount USD", "Sales tax USD", "Record ID"]];
  for (const [label, cents] of statementLines(report)) rows.push(["P&L", "", "", label, report.draft ? "Draft" : "Cash basis", (cents / 100).toFixed(2), "", ""]);
  for (const row of report.receipts) rows.push(["Receipt", row.date, row.reference, row.invoice ?? "", "", (row.net / 100).toFixed(2), (row.tax / 100).toFixed(2), row.id]);
  for (const row of report.expenses) rows.push([row.classification, row.business_date, row.vendor, row.description, row.category ?? "", row.amount_cents * (row.classification === "business refund" ? -1 : 1) / 100, "", row.id]);
  for (const row of report.exceptions) rows.push(["Excluded receipt", row.date ?? "", row.reference, row.invoice ?? "", row.reason, (row.gross / 100).toFixed(2), "", row.id]);
  for (const row of report.receivable) rows.push(["Current ledger receivable", row.due_date ?? "", row.display_id ?? "", row.customer_name ?? "", row.overdue ? "Overdue" : "Current", (row.cents / 100).toFixed(2), "", row.id]);
  return rows.map(row => row.map(value => {
    const text = String(value);
    const safe = typeof value === "string" && /^[\s]*[=+@\-\t\r\n]/.test(text) && !/^-?\d+(?:\.\d+)?$/.test(text) ? "'" + text : text;
    return '"' + safe.replace(/"/g, '""') + '"';
  }).join(",")).join("\r\n");
}
